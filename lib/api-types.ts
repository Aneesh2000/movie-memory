import { z } from "zod";

/**
 * The API contract, shared by route handlers (server) and lib/api.ts (client).
 * Response shapes are zod schemas so the client validates what it receives at
 * runtime instead of trusting a cast.
 */

// ----- Errors ---------------------------------------------------------------

export const API_ERROR_CODES = [
  "UNAUTHORIZED", // 401: no or expired session
  "VALIDATION_ERROR", // 400: bad input
  "NO_MOVIE", // 409: user has not completed onboarding
  "FACT_PENDING", // 503: another request is generating a fact right now
  "FACT_UNAVAILABLE", // 503: OpenAI failed and there is nothing cached
  "INTERNAL", // 500: anything unexpected
  // Client-only codes (never sent by the server):
  "NETWORK_ERROR",
  "BAD_RESPONSE",
] as const;

export type ApiErrorCode = (typeof API_ERROR_CODES)[number];

export const apiErrorBodySchema = z.object({
  error: z.object({
    code: z.enum(API_ERROR_CODES),
    message: z.string(),
  }),
});
export type ApiErrorBody = z.infer<typeof apiErrorBodySchema>;

// ----- GET /api/me ----------------------------------------------------------

export const meResponseSchema = z.object({
  user: z.object({
    id: z.string(),
    name: z.string().nullable(),
    email: z.string().nullable(),
    image: z.string().nullable(),
    favoriteMovie: z.string().nullable(),
  }),
});
export type MeResponse = z.infer<typeof meResponseSchema>;

// ----- PUT /api/me/movie ----------------------------------------------------

export type UpdateMovieRequest = { movie: string };

export const updateMovieResponseSchema = z.object({
  favoriteMovie: z.string(),
});
export type UpdateMovieResponse = z.infer<typeof updateMovieResponseSchema>;

// ----- GET /api/fact --------------------------------------------------------

/**
 * Where the fact came from:
 * - fresh:    generated by this request
 * - cache:    newer than 60s, reused (server cache window)
 * - stale:    older than 60s, returned because another request is generating
 * - fallback: older than 60s, returned because OpenAI failed
 */
export const FACT_SOURCES = ["fresh", "cache", "stale", "fallback"] as const;
export type FactSource = (typeof FACT_SOURCES)[number];

export const factResponseSchema = z.object({
  fact: z.object({
    id: z.string(),
    movie: z.string(),
    content: z.string(),
    createdAt: z.iso.datetime(),
  }),
  source: z.enum(FACT_SOURCES),
  /** When the server will next generate a new fact instead of reusing this one. */
  freshUntil: z.iso.datetime(),
});
export type FactResponse = z.infer<typeof factResponseSchema>;
